// Turns the built frontend into a C++ include the mod compiles in, so the mod can
// serve the map page itself.
//   node scripts/embed-web.mjs <dist-dir> <out.inc>
// Default: web/dist -> Mod/LiveMap/Source/LiveMap/Private/Core/WebAssets.inc
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, extname, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dist = resolve(process.argv[2] ?? join(root, "web/dist"));
const out = resolve(process.argv[3] ?? join(root, "Mod/LiveMap/Source/LiveMap/Private/Core/WebAssets.inc"));

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".json": "application/json",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".ico": "image/x-icon",
  ".woff2": "font/woff2",
  ".txt": "text/plain; charset=utf-8",
};

function walk(dir) {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = walk(dist).filter((p) => !p.endsWith(".map")).sort();
if (!files.some((p) => relative(dist, p) === "index.html")) {
  console.error(`no index.html in ${dist}; run npm run build in web/ first`);
  process.exit(1);
}

let src = "// Generated by scripts/embed-web.mjs from web/dist. Do not edit or commit.\n#pragma once\n\n";
const entries = [];
let total = 0;
files.forEach((p, i) => {
  const data = readFileSync(p);
  total += data.length;
  const urlPath = "/" + relative(dist, p).split("\\").join("/");
  const type = TYPES[extname(p).toLowerCase()] ?? "application/octet-stream";
  // Byte arrays, not string literals: MSVC caps string literals at 64 KB.
  const bytes = [];
  for (let o = 0; o < data.length; o += 32) {
    bytes.push("\t" + Array.from(data.subarray(o, o + 32), (b) => b + ",").join(""));
  }
  src += `static const unsigned char LiveMapWebData${i}[] = {\n${bytes.join("\n")}\n};\n`;
  entries.push(`\t{"${urlPath}", "${type}", LiveMapWebData${i}, sizeof(LiveMapWebData${i})},`);
});
src += `\nstatic const livemap::EmbeddedFile LiveMapWebFiles[] = {\n${entries.join("\n")}\n};\n`;
src += `static const size_t LiveMapWebFileCount = ${files.length};\n`;
writeFileSync(out, src);
console.log(`embedded ${files.length} files (${(total / 1024).toFixed(0)} KB) -> ${relative(root, out)}`);
